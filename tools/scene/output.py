"""The scene's output side: the layer and manifest-entry shapes, baking a layer, checking its conditions, writing the
manifest, and compositing each stage into a preview."""
from __future__ import annotations

import json
import os
from pathlib import Path
from typing import NotRequired, TypedDict

from PIL import Image, ImageChops

import depth
import grades
import kit
from drift import source_digest
from place import H, W, canvas
from stages import CONDITIONS, KINDS, STAGES, State, holds
from tints import BAKES, WOOD


ASSETS = Path(os.environ.get("ASHFALL_ASSETS", "~/.local/share/ostmere/assets")).expanduser()
OUT = ASSETS / "art/scene"
PREVIEW = ASSETS / "previews/scene"


class Layer(TypedDict):
    """A drawn layer before it is cut out and written: `until` hides it again, `blend` is a mix-blend-mode, `ungraded`
    layers are drawn over the grade, and `front`
    layers over those: they stand in front of the lights, on the page's second canvas."""
    id: str
    img: Image.Image
    when: str
    until: NotRequired[str]
    blend: NotRequired[str]
    ungraded: NotRequired[bool]
    front: NotRequired[bool]


class Entry(TypedDict):
    """A layer as the manifest lists it: where its cut-out sits and when it shows."""
    id: str
    src: str
    x: int
    y: int
    when: str
    until: NotRequired[str]
    blend: NotRequired[str]
    ungraded: NotRequired[bool]
    front: NotRequired[bool]
    base: NotRequired[int]


def bake(layer: Layer) -> Image.Image:
    """Grade per layer (lights are already the colour they mean), then cut to the drawn pixels."""
    img = layer["img"]
    if layer.get("blend") is None and layer["id"] != "ash":
        params = BAKES.get(layer["id"], WOOD)
        if params:
            img = kit.grade(img, **params)
    return img



def check_conditions(entries: list[Entry]) -> None:
    """Every `when`/`until` is built of known kinds, joined by | (any) and & (all): the page treats an unknown one as
    never holding, so a typo would hide a layer without a word."""
    for e in entries:
        for field in ("when", "until"):
            for term in (e.get(field) or "always").split("|"):
                for atom in term.split("&"):
                    kind = atom.partition(":")[0]
                    if kind not in KINDS or (kind != "always" and ":" not in atom):
                        raise ValueError(f"{e['id']}.{field}: unknown condition {atom!r}")


def write_manifest(entries: list[Entry]) -> None:
    manifest = {
        "size": [W, H],
        "pixelated": True,
        "layers": entries,
        "source": source_digest(),
        "grades": grades.GRADES,
        "conditions": CONDITIONS,
        "note": "Generated by tools/scene/build.py; never hand-edited. Layers stack in order, except that layers with a "
                "`base` (the y of their ground contact) are drawn in order of it (tools/scene/depth.py); `until` hides a layer "
                "again; `blend` is a mix-blend-mode. Draw at an integer multiple of size with image-rendering: "
                "pixelated. A grade is a CSS filter on the scene plus an overlay colour; cold is the default and a "
                "later grade whose `when` holds replaces it. `ungraded` layers (the player's fire) are drawn over the grade; `front` layers "
                "(figures standing before the fire) are drawn on a second canvas over those, graded like the rest.",
    }
    (OUT / "manifest.json").write_text(json.dumps(manifest, indent=1) + "\n")


def composite(entries: list[Entry], state: State) -> Image.Image:
    """What the page shows for a state: visible layers stacked (screen-blended lights), then the grade."""
    img = Image.new("RGBA", (W, H), (0, 0, 0, 255))
    behind = [e for e in entries if not e.get("ungraded") and not e.get("front")]
    front = [e for e in entries if e.get("front")]
    grade = grades.pick(lambda cond: holds(cond, state))
    graded = grades.apply(_stack(img, behind, state), grade).convert("RGBA")
    lit = _stack(graded, [e for e in entries if e.get("ungraded")], state)
    if not front:
        return lit
    mask = _stack(Image.new("RGBA", (W, H), (0, 0, 0, 0)), front, state).getchannel("A")
    with_front = grades.apply(_stack(_stack(img, behind, state), front, state), grade).convert("RGBA")
    glows = [e for e in entries if e.get("ungraded") and e.get("blend")]
    return Image.composite(_stack(with_front, glows, state), lit, mask)


def check_depth(entries: list[Entry]) -> None:
    """No stage draws a layer over one the depth puts in front of it where their pixels meet (depth.misdrawn): the
    page's ungraded and front passes go over everything in the passes before them, whatever stands nearer."""
    masks: dict[str, Image.Image] = {}

    def mask(e: Entry) -> Image.Image:
        if e["id"] not in masks:
            alpha = Image.open(OUT / e["src"].split("?")[0]).convert("RGBA").getchannel("A")
            masks[e["id"]] = Image.new("1", (W, H))
            masks[e["id"]].paste(kit.point(alpha, lambda v: 255 if v else 0).convert("1"), (e["x"], e["y"]))
        return masks[e["id"]]

    by_id = {e["id"]: e for e in entries}

    def overlap(a: str, b: str) -> bool:
        return ImageChops.logical_and(mask(by_id[a]), mask(by_id[b])).getbbox() is not None

    faults: dict[tuple[str, str], str] = {}
    for stage, state in STAGES.items():
        shown = [e for e in entries if holds(e["when"], state) and not ("until" in e and holds(e["until"], state))]
        for pair in depth.misdrawn(shown, overlap):
            faults.setdefault(pair, stage)
    new = {pair: stage for pair, stage in faults.items() if pair not in depth.HELD_MISDRAWN}
    if new:
        raise ValueError("drawn over what stands in front of it: "
                         + "; ".join(f"{near} under {far} ({stage})" for (near, far), stage in new.items()))
    if stale := depth.HELD_MISDRAWN - faults.keys():
        raise ValueError(f"depth.HELD_MISDRAWN holds pairs no longer misdrawn, drop them: {sorted(stale)}")


def _stack(img: Image.Image, entries: list[Entry], state: State) -> Image.Image:
    for e in depth.draw_order(entries):
        if not holds(e["when"], state) or ("until" in e and holds(e["until"], state)):
            continue
        sprite = Image.open(OUT / e["src"].split("?")[0]).convert("RGBA")
        layer = canvas()
        layer.alpha_composite(sprite, (e["x"], e["y"]))
        img = grades.screen(img, layer) if e.get("blend") == "screen" else Image.alpha_composite(img, layer)
    return img


def write_previews(entries: list[Entry]) -> None:
    """Each stage at 2x (960 wide, the desktop size) and scaled to 390 wide (a phone)."""
    PREVIEW.mkdir(parents=True, exist_ok=True)
    for stage, state in STAGES.items():
        img = composite(entries, state)
        kit.resize(img, (W * 2, H * 2)).save(PREVIEW / f"{stage}.png", optimize=True)

