"""The scene's output side: the layer and manifest-entry shapes, baking a layer, checking its conditions, writing the
manifest, and compositing each stage into a preview."""
from __future__ import annotations

import json
import os
from collections.abc import Callable, Sequence
from pathlib import Path
from typing import Literal, NotRequired, TypedDict

from PIL import Image, ImageChops

import builds
import depth
import grades
import kit
import views
from drift import source_digest
from place import H, W, canvas
from storeset import write_list
from stages import CONDITIONS, KINDS, STAGES, State, holds
from tints import BAKES, WOOD


ASSETS = Path(os.environ.get("ASHFALL_ASSETS", "~/.local/share/ostmere/assets")).expanduser()
OUT = ASSETS / "art/scene"
PREVIEW = ASSETS / "previews/scene"


class Layer(TypedDict):
    """A drawn layer before it is cut out and written: `until` hides it again, `blend` is a mix-blend-mode, `ungraded`
    layers are drawn over the grade, and `front`
    layers over those: they stand in front of the lights, on the page's second canvas. `open_fire` marks a fire's
    layers (ring, kindling, flames, ghosts) that stand on open ground: no stage may lay one over a wall."""
    id: str
    img: Image.Image
    when: str
    until: NotRequired[str]
    blend: NotRequired[str]
    ungraded: NotRequired[bool]
    front: NotRequired[bool]
    flicker: NotRequired[float]
    sound: NotRequired[Literal["fire", "evening"]]
    open_fire: NotRequired[bool]


class Entry(TypedDict):
    """A layer as the manifest lists it: where its cut-out sits and when it shows."""
    id: str
    src: str
    x: int
    y: int
    when: str
    until: NotRequired[str]
    blend: NotRequired[str]
    ungraded: NotRequired[bool]
    front: NotRequired[bool]
    flicker: NotRequired[float]
    sound: NotRequired[Literal["fire", "evening"]]
    open_fire: NotRequired[bool]
    base: NotRequired[int]


def bake(layer: Layer) -> Image.Image:
    """Grade per layer (lights are already the colour they mean), then cut to the drawn pixels."""
    img = layer["img"]
    if layer.get("blend") is None and layer["id"] != "ash":
        params = BAKES.get(layer["id"], WOOD)
        if params:
            img = kit.grade(img, **params)
    return img



def check_conditions(entries: list[Entry]) -> None:
    """Every `when`/`until` is built of known kinds, joined by | (any) and & (all): the page treats an unknown one as
    never holding, so a typo would hide a layer without a word."""
    for e in entries:
        for field in ("when", "until"):
            _check_condition(f"{e['id']}.{field}", e.get(field))
    for v in views.VIEWS:
        _check_condition(f"view {v.id}.when", v.when)


def _check_condition(label: str, cond: str | None) -> None:
    for term in (cond or "always").split("|"):
        for atom in term.split("&"):
            kind = atom.partition(":")[0]
            if kind not in KINDS or (kind != "always" and ":" not in atom):
                raise ValueError(f"{label}: unknown condition {atom!r}")


def write_manifest(entries: list[Entry]) -> None:
    manifest = {
        "size": [W, H],
        "views": views.manifest(),
        "pixelated": True,
        "layers": entries,
        "source": source_digest(),
        "grades": grades.GRADES,
        "conditions": CONDITIONS,
        "note": "Generated by tools/scene/build.py; never hand-edited. Layers stack in order, except that layers with a "
                "`base` (the y of their ground contact) are drawn in order of it (tools/scene/depth.py); `until` hides a layer "
                "again; `blend` is a mix-blend-mode. Draw at an integer multiple of size with image-rendering: "
                "pixelated. A grade is a CSS filter on the scene plus an overlay colour; cold is the default and a "
                "later grade whose `when` holds replaces it. `ungraded` layers (the player's fire) are drawn over the grade; `front` layers "
                "(figures standing before the fire) are drawn on a second canvas over those, graded like the rest.",
    }
    (OUT / "manifest.json").write_text(json.dumps(manifest, indent=1) + "\n")
    write_list(entries, grades.GRADES)


def composite(entries: list[Entry], state: State) -> Image.Image:
    """What the page shows for a state: visible layers stacked (screen-blended lights), then the grade."""
    img = Image.new("RGBA", (W, H), (0, 0, 0, 255))
    behind = [e for e in entries if not e.get("ungraded") and not e.get("front")]
    front = [e for e in entries if e.get("front")]
    grade = grades.pick(lambda cond: holds(cond, state))
    graded = grades.apply(_stack(img, behind, state), grade).convert("RGBA")
    lit = _stack(graded, [e for e in entries if e.get("ungraded")], state)
    if not front:
        return lit
    mask = _stack(Image.new("RGBA", (W, H), (0, 0, 0, 0)), front, state).getchannel("A")
    with_front = grades.apply(_stack(_stack(img, behind, state), front, state), grade).convert("RGBA")
    glows = [e for e in entries if e.get("ungraded") and e.get("blend")]
    return Image.composite(_stack(with_front, glows, state), lit, mask)


def check_depth(entries: list[Entry]) -> None:
    """No stage draws a layer over one the depth puts in front of it where their pixels meet (depth.misdrawn): the
    page's ungraded and front passes go over everything in the passes before them, whatever stands nearer."""
    overlap = _overlap(entries)
    faults: dict[tuple[str, str], str] = {}
    for stage, state in STAGES.items():
        shown = [e for e in entries if holds(e["when"], state) and not ("until" in e and holds(e["until"], state))]
        for pair in depth.misdrawn(shown, overlap):
            faults.setdefault(pair, stage)
    new = {pair: stage for pair, stage in faults.items() if pair not in depth.HELD_MISDRAWN}
    if new:
        raise ValueError("drawn over what stands in front of it: "
                         + "; ".join(f"{near} under {far} ({stage})" for (near, far), stage in new.items()))
    if stale := depth.HELD_MISDRAWN - faults.keys():
        raise ValueError(f"depth.HELD_MISDRAWN holds pairs no longer misdrawn, drop them: {sorted(stale)}")


def check_footing(entries: list[Entry]) -> None:
    """No figure's footing lies on a wall it stands in front of (depth.on_walls), and no `open_fire` layer lies on any wall
    (depth.fire_on_walls), in any stage: a seat or a spot a wall's courses grow over later fails here, naming the
    stage. Fails too when no stage had a figure and a wall together."""
    if gone := depth.missing_walls(entries):
        raise ValueError(f"depth.WALLS names layers the scene no longer has, or no layer is `open_fire`: {gone}")
    overlap, whole = _overlap(entries, footing=True), _overlap(entries)
    faults: dict[tuple[str, str], str] = {}
    met = 0
    for stage, state in STAGES.items():
        shown = [e for e in entries if holds(e["when"], state) and not ("until" in e and holds(e["until"], state))]
        met += any(e["id"] in depth.WALLS for e in shown) and any(e["id"].startswith("figure_") for e in shown)
        for pair in depth.on_walls(shown, overlap):
            faults.setdefault(pair, stage)
        for pair in depth.fire_on_walls(shown, whole):
            faults.setdefault(pair, stage)
    if not met:
        raise ValueError("no stage shows a figure and a wall together: the footing check looked at nothing")
    if faults:
        raise ValueError("a figure's feet or an open fire lie on a wall: "
                         + "; ".join(f"{f} on {w} ({s})" for (f, w), s in faults.items()))


def check_builds(entries: list[Entry]) -> None:
    """No two builds share `builds.MIN_SHARED` pixels at any stage, bar the pairs `builds.HELD_CROWDED` holds, and every
    layer is classified (`builds.unsorted`). Fails too when no stage showed two builds together: nothing was compared."""
    if bad := builds.unsorted(entries):
        raise ValueError(f"layers in no build and not in builds.NOT_BUILDS, or named there and gone: {bad}")
    masks: dict[tuple[str, ...], Image.Image] = {}
    by_id = {e["id"]: e for e in entries}

    def union(ids: Sequence[str]) -> Image.Image:
        key = tuple(ids)
        if key not in masks:
            masks[key] = Image.new("1", (W, H))
            for i in ids:
                masks[key] = ImageChops.lighter(masks[key], _alpha_mask(by_id[i]))
        return masks[key]

    def shared(a: Sequence[str], b: Sequence[str]) -> int:
        first, second = union(a), union(b)
        if not (box := first.getbbox()) or not second.getbbox() or not _meets(box, second.getbbox()):
            return 0
        return ImageChops.logical_and(first, second).histogram()[255]

    faults: dict[tuple[str, str], str] = {}
    compared = 0
    for stage, state in STAGES.items():
        shown = [e for e in entries if holds(e["when"], state) and not ("until" in e and holds(e["until"], state))]
        compared += len({builds.MEMBER_OF[e["id"]] for e in shown if e["id"] in builds.MEMBER_OF}) > 1
        for a, b, px in builds.crowded(shown, shared):
            faults.setdefault((a, b), f"{stage}, {px} px")
    if not compared:
        raise ValueError("no stage shows two builds together: the overlap check looked at nothing")
    if new := {pair: at for pair, at in faults.items() if pair not in builds.HELD_CROWDED}:
        raise ValueError("builds drawn over each other: " + "; ".join(f"{a} and {b} ({at})" for (a, b), at in new.items()))
    if stale := builds.HELD_CROWDED - faults.keys():
        raise ValueError(f"builds.HELD_CROWDED holds pairs that no longer overlap, drop them: {sorted(stale)}")


def _meets(a: tuple[int, int, int, int], b: tuple[int, int, int, int] | None) -> bool:
    return b is not None and a[0] < b[2] and b[0] < a[2] and a[1] < b[3] and b[1] < a[3]


def _alpha_mask(e: Entry) -> Image.Image:
    """The layer's drawn pixels, placed on the scene's canvas."""
    alpha = Image.open(OUT / e["src"].split("?")[0]).convert("RGBA").getchannel("A")
    out = Image.new("1", (W, H))
    out.paste(kit.point(alpha, lambda v: 255 if v else 0).convert("1"), (e["x"], e["y"]))
    return out


def _overlap(entries: list[Entry], footing: bool = False) -> Callable[[str, str], bool]:
    """Whether two layers' pixels meet; with `footing`, whether the first's bottom `depth.FEET` rows meet the second's."""
    masks: dict[str, Image.Image] = {}
    by_id = {e["id"]: e for e in entries}

    def mask(e: Entry) -> Image.Image:
        if e["id"] not in masks:
            masks[e["id"]] = _alpha_mask(e)
        return masks[e["id"]]

    def feet(e: Entry) -> Image.Image:
        whole, bottom = mask(e), e["y"] + Image.open(OUT / e["src"].split("?")[0]).height
        band = Image.new("1", (W, H))
        band.paste(whole.crop((0, bottom - depth.FEET, W, bottom)), (0, bottom - depth.FEET))
        return band

    def overlap(a: str, b: str) -> bool:
        first = feet(by_id[a]) if footing else mask(by_id[a])
        return ImageChops.logical_and(first, mask(by_id[b])).getbbox() is not None

    return overlap


def _stack(img: Image.Image, entries: list[Entry], state: State) -> Image.Image:
    for e in depth.draw_order(entries):
        if not holds(e["when"], state) or ("until" in e and holds(e["until"], state)):
            continue
        sprite = Image.open(OUT / e["src"].split("?")[0]).convert("RGBA")
        layer = canvas()
        layer.alpha_composite(sprite, (e["x"], e["y"]))
        img = grades.screen(img, layer) if e.get("blend") == "screen" else Image.alpha_composite(img, layer)
    return img


def write_previews(entries: list[Entry]) -> None:
    """Each stage at 2x (960 wide, the desktop size) and scaled to 390 wide (a phone)."""
    PREVIEW.mkdir(parents=True, exist_ok=True)
    for stage, state in STAGES.items():
        w, h = views.pick(state).size
        kit.resize(composite(entries, state).crop((0, 0, w, h)), (w * 2, h * 2)).save(PREVIEW / f"{stage}.png", optimize=True)

